use super::CommonArgs;

/// Annotates each CDS or protein with features found by a detection algorithm rather
/// than a reference search: PROSITE motifs, and upstream's TMbed (upstream
/// `find_features.py`).
#[derive(clap::Args, Clone, Debug, Default)]
#[command(rename_all = "snake_case")]
pub struct FindFeaturesArgs {
    #[command(flatten)]
    pub common: CommonArgs,
    /// The genbank or fasta files to annotate. Genbank files can be nucleotide (with
    /// CDS annotations) or peptide. Fasta files must be peptide.
    #[arg(short, long, required = true, num_args = 1..)]
    pub input: Vec<String>,
    /// Whether the sequences in FASTA inputs are protein or nucleotide. GenBank records
    /// declare their own molecule type.
    #[arg(long, default_value = "protein", value_parser = ["nucleotide", "protein"])]
    pub alphabet: String,
    /// Write the records to this GenBank file. Use - for standard output.
    #[arg(short = 'o', long)]
    pub genbank_out: Option<String>,
    /// Write the records to this FASTA file. Use - for standard output.
    #[arg(long)]
    pub fasta_out: Option<String>,
    /// The number of CPU threads to use. 0: one per physical core.
    #[arg(long, default_value_t = 0, allow_negative_numbers = true)]
    pub cpu: i64,
    /// When activated, new CDS annotations will be added with Prodigal in Metagenomic
    /// mode. If 'all', then any existing CDS annotations will be deleted and all contigs
    /// will be re-annotated. If 'unannotated', then only contigs without CDS
    /// annotations will be annotated. If you supply a nucleotide fasta file, be sure to
    /// also specify --alphabet nucleotide.
    #[arg(long, value_parser = ["all", "unannotated"])]
    pub gene_call: Option<String>,
    /// Run TMbed transmembrane and signal peptide prediction. Not supported by
    /// domainatoredux: giving it is an error.
    #[arg(long)]
    pub tmbed: bool,
    /// PROSITE motifs to search for, in the syntax of EMBOSS fuzzpro
    /// (<https://emboss.sourceforge.net/apps/release/6.5/emboss/apps/fuzzpro.html>).
    /// Example: `[DE](2)HS{P}X(2)PX(2,4)C` matches two Asp/Glu, then His, Ser, any except Pro,
    /// two of any, Pro, two to four of any, Cys. Motif names for boolean expressions are
    /// auto-generated by sanitizing the pattern (replacing parentheses and dashes with
    /// underscores).
    #[arg(long, num_args = 1..)]
    pub motif: Option<Vec<String>>,
    /// Batch size for sequence processing. Accepted for compatibility with upstream,
    /// where only TMbed uses it.
    #[arg(long, default_value_t = 4000, allow_negative_numbers = true)]
    pub batch_size: i64,
    /// For models that can use GPU acceleration, the device to run on. Accepted for
    /// compatibility with upstream, where only TMbed uses it.
    #[arg(long, default_value = "cuda:0")]
    pub device: String,
    /// Base directory for algorithm model weights. Accepted for compatibility with
    /// upstream, where only TMbed uses it.
    #[arg(long)]
    pub model_dir: Option<String>,
    /// Directory for TMbed's ProtT5 encoder model. Accepted for compatibility with
    /// upstream, where only TMbed uses it.
    #[arg(long)]
    pub tmbed_model_dir: Option<String>,
    /// Which CDSs/proteins to annotate, by fragment status (partial proteins). include:
    /// all (the default). exclude: skip fragments. only: only fragments. A CDS is a
    /// fragment if its location has '<' or '>', or it has a /partial qualifier. A
    /// protein record is a fragment if it has a UniProt ' (Fragment)' or MGnify 'FL=0'
    /// header, a 'Flags: Fragment' definition or NON_TER features (UniProt text
    /// entries), or a CDS/Protein feature with '<' or '>' spanning it.
    #[arg(long, default_value = "include", value_parser = ["include", "exclude", "only"])]
    pub partial: String,
}
